/** Code-mode execution for Programmable States — the `ProgramDef.Code`
 * counterpart to `an1mbyt3_runtime::graph::evaluate_graph` (the `Graph`
 * counterpart), except this one runs entirely here in the frontend: nothing
 * in the Rust engine parses or executes a Code program's source string (see
 * `an1mbyt3_core::program`'s module doc for why that's a deliberate,
 * accepted tradeoff — a Graph program is real Rust and runs everywhere,
 * including an exported/embedded player; a Code program only ever runs
 * inside this desktop editor's own frontend loop, driven by `App.tsx`'s
 * `frame()`).
 *
 * The scripting surface is deliberately DOM-shaped, not `ctx`-method-shaped:
 * `let square = getCompByID('shape(0)')` / `getCompByClass('enemy')`
 * mirror `document.getElementById`/`getElementsByClassName`, and the
 * returned component ref exposes plain settable properties (`square.x`,
 * `square.rotation`, ...) rather than an on-canvas method call per
 * property — closer to how anyone who's touched web/DOM scripting already
 * thinks, which is the whole point of choosing this shape over a bespoke
 * API. `getCompByID`/`getCompByClass` select against `an1mbyt3_core::Node::id`/
 * `classes` — see that Rust type's own doc comment for the "unique,
 * autogenerated `shape(<serial>)` by default, but freely renamable" id
 * convention, and the Inspector's Id/Classes fields that author them.
 *
 * Compiled via `new Function('ctx', 'getCompByID', 'getCompByClass',
 * 'spawnClone', 'deleteNode', source)` — the same "authored string, compiled
 * and cached by identity, never touched by the engine itself" shape
 * `NodeGraphEditor`'s own `program.value` holds for a `Graph`, just
 * executable instead of data. Cached so an unchanged script isn't re-parsed
 * every single frame; only actually re-parsed when its source text changes
 * (a fresh edit in the Program editor's code panel).
 *
 * `spawnClone(ref)`/`deleteNode(ref)` take a `ComponentRef` directly, not a
 * raw node id — a script never needs (or can get) the real opaque `NodeId`
 * `ctx.spawnClone`/`ctx.deleteNode` operate on internally; see the
 * `componentOpaqueIds` WeakMap below for how a ref's hidden opaque id is
 * tracked and resolved.
 */

